    plt.colorbar(scm, ax=ax[2], label=r"$\log_{10} T$")
    finish(fig, "ml_dataset_overview")

    # ---- 2. residuals ----
    fig, ax = plt.subplots(1, 3, figsize=(13, 3.8))
    s = d.sample(6000, random_state=SEED)
    ax[0].axhline(0, color="black", lw=1)
    ax[0].scatter(s["m"], s["residual"], s=3, alpha=0.3, color="#b5483d")
    ax[0].set_xlabel("m"); ax[0].set_ylabel("residual  (currency, K=100)")
    ax[0].set_title("residual vs moneyness")

    # A raw scatter against T is an uninformative blob, because the residual
    # is dominated by m at every maturity. The maturity effect is in the
    # SPREAD, so the binned mean |residual| is overlaid.
    ax[1].axhline(0, color="black", lw=1)
    ax[1].scatter(s["T"], s["residual"], s=3, alpha=0.18, color="#b5483d")
    tb = np.logspace(np.log10(d["T"].min()), np.log10(d["T"].max()), 16)
    ctr = np.sqrt(tb[:-1] * tb[1:])
    idx = np.digitize(d["T"], tb) - 1
    mabs = np.array([np.abs(d["residual"].to_numpy()[idx == i]).mean()
                     if (idx == i).any() else np.nan for i in range(len(ctr))])
    ax[1].plot(ctr, mabs, color="black", lw=2, marker="o", ms=3,
               label=r"mean $|e|$")
    ax[1].plot(ctr, -mabs, color="black", lw=2, marker="o", ms=3)
    ax[1].set_xscale("log")
    ax[1].set_xlabel("T  (years, log scale)"); ax[1].set_ylabel("residual")
    ax[1].set_title("residual vs maturity: spread narrows with T")
    ax[1].legend(fontsize=8, loc="lower right")

    # binned mean residual over (m, T): the convexity signature
    mb = np.linspace(-0.6, 0.6, 25)
    tb = np.logspace(np.log10(d["T"].min()), np.log10(d["T"].max()), 20)
    H, _, _ = np.histogram2d(d["m"], d["T"], bins=[mb, tb],
                             weights=d["residual"])
    C, _, _ = np.histogram2d(d["m"], d["T"], bins=[mb, tb])
    with np.errstate(invalid="ignore"):
        Mn = np.where(C > 0, H / np.maximum(C, 1), np.nan)
    lim = np.nanmax(np.abs(Mn))
    im = ax[2].pcolormesh(mb, tb, Mn.T, cmap="RdBu_r", vmin=-lim, vmax=lim)
    ax[2].set_yscale("log")
    ax[2].set_xlabel("m"); ax[2].set_ylabel("T  (log scale)")
    ax[2].set_title("mean residual over (m, T)")
    plt.colorbar(im, ax=ax[2], label="mean residual")
    finish(fig, "regression_residuals")

    # ---- 3. ridge selection ----
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.8))
    for name, tab in alpha_tables.items():
        a = [t[0] for t in tab]
        v = [t[1] * K_REF for t in tab]
        ax[0].plot(a, v, marker="o", ms=3, label=name)
        ax[0].axvline(a[int(np.argmin(v))], ls=":", lw=1)
    ax[0].set_xscale("log")
    ax[0].set_xlabel(r"ridge penalty $\alpha$")
    ax[0].set_ylabel("validation RMSE (currency)")
    ax[0].set_title("alpha chosen on validation only")
    ax[0].legend(fontsize=8)

    sc, ols, ridge, feats = fitted["basic [m,T,r,sigma]"]
    Xtr, ytr = get_xy(df, feats, split="train")
